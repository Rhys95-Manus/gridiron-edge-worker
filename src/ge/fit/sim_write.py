"""Fit v5 = fit v4 plus the Phase 5 keys (ruling B1, 2026-10-23). Every v4 entry (values,
missing, no-signal) is copied unchanged; a Phase 5 key that would replace a v4 key is refused.
The file's provenance fields (data digest, code commit) describe the v5 run; its header line
names the base version."""

from __future__ import annotations

import datetime as dt
from collections.abc import Mapping
from pathlib import Path
from typing import Any

import yaml

from ge.config import ATTRIBUTION, FittedFile


def write_v5(
    root: Path,
    window: str,
    *,
    values: Mapping[str, Mapping[str, Any]],
    missing: Mapping[str, str],
    no_signal: Mapping[str, str],
    data_digest: str,
    code_commit: str,
    base: str = "v4",
    version: str = "v5",
    data_as_of: dt.datetime | None = None,
) -> Path:
    """`data_as_of` is the Phase 5 run's data cut (the base's entries keep their own, named in
    the header line); None keeps the base file's."""
    src = root / base / f"{window}.yaml"
    old = yaml.safe_load(src.read_text(encoding="utf-8"))
    for section, new in (("values", values), ("missing", missing), ("no_signal", no_signal)):
        clash = sorted(set(new) & set(old.get(section) or {}))
        clash += sorted(
            k for k in new for s in ("values", "missing", "no_signal") if k in (old.get(s) or {})
        )
        if clash:
            raise ValueError(f"Phase 5 keys would replace {base} entries: {sorted(set(clash))}")
    body = {
        "fit_version": version,
        "window": old["window"],
        "test_season": old["test_season"],
        "seasons": old["seasons"],
        "data_as_of": data_as_of.isoformat() if data_as_of is not None else old["data_as_of"],
        "data_digest": data_digest,
        "code_commit": code_commit,
        "attribution": ATTRIBUTION,
        "values": dict(sorted({**old["values"], **values}.items())),
        "missing": dict(sorted({**(old.get("missing") or {}), **missing}.items())),
        "no_signal": dict(sorted({**(old.get("no_signal") or {}), **no_signal}.items())),
    }
    FittedFile.model_validate(body)
    out = root / version / f"{window}.yaml"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        f"# Fit {version} = {base} (every entry unchanged, data cut {old['data_as_of']}) plus the "
        "Phase 5 (PRJ-02, MTC-05, ENV, PLY-14) fits. Generated by `ge fit-sim`; do not edit.\n"
        + yaml.safe_dump(body, sort_keys=False, allow_unicode=True, width=100),
        encoding="utf-8",
        newline="\n",
    )
    return out
